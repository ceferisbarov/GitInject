import os

import click

from .gh_client import GitHubClient


class ProvisioningError(RuntimeError):
    pass


class RepoProvisioner:
    """Handles the physical setup of a GitHub repository for benchmarking."""

    def __init__(self, gh_client: GitHubClient):
        self.gh_client = gh_client
        self._owns_repo = False

    @staticmethod
    def _require(result, operation):
        success, error = result
        if not success:
            raise ProvisioningError(f"{operation}: {error}")

    def provision(
        self,
        workflow_dir: str,
        required_files: dict = None,
        branch: str = None,
        template_repo: str = None,
        secrets: dict = None,
        variables: dict = None,
        substitution_map: dict = None,
    ):
        """Create and configure a fresh repository, failing on incomplete setup."""
        if self._owns_repo:
            raise ProvisioningError("A previously created repository still needs cleanup")
        creation = self.gh_client.fork_repo(template_repo) if template_repo else self.gh_client.create_repo(public=True)
        self._require(creation, "Create repository")
        self._owns_repo = True
        if template_repo:
            self.gh_client.wait_until_ready()
        else:
            self._require(
                self.gh_client.put_file(
                    "README.md", "# Benchmark Repository\nGenerated by AI Benchmark Suite.", "initial commit", "main"
                ),
                "Initialize repository",
            )
        repo_info = self.gh_client.get_repo_info()
        if not repo_info:
            raise ProvisioningError("Created repository is not readable")
        default_branch = repo_info.get("defaultBranchRef", {}).get("name") or "main"
        target_branch = branch or default_branch
        self._require(self.gh_client.enable_actions(), "Enable Actions")
        self._require(self.gh_client.set_fork_pr_approval_policy(), "Set fork approval policy")
        self._require(self.gh_client.enable_issues(), "Enable issues")
        for operation, values in ((self.gh_client.set_secret, secrets), (self.gh_client.set_variable, variables)):
            for name, value in (values or {}).items():
                if value is None or value == "":
                    raise ProvisioningError(f"Empty configuration value: {name}")
                self._require(operation(name, value), f"Set configuration {name}")
        contents_dir = os.path.join(workflow_dir, "contents")
        workflow_files = {}
        if os.path.isdir(contents_dir):
            for root, _, filenames in os.walk(contents_dir):
                for filename in filenames:
                    local_path = os.path.join(root, filename)
                    workflow_files[os.path.relpath(local_path, contents_dir)] = local_path
        elif os.path.isdir(workflow_dir):
            for filename in os.listdir(workflow_dir):
                if filename.endswith((".yml", ".yaml")):
                    workflow_files[f".github/workflows/{filename}"] = os.path.join(workflow_dir, filename)
        scenario_files = required_files or {}
        for path in scenario_files:
            if path in workflow_files:
                raise ProvisioningError(f"File defined by both workflow and scenario: {path}")
        additions = {path: self._get_content(path, content, substitution_map) for path, content in workflow_files.items()}
        self._require(
            self.gh_client.batch_sync(additions, [".github/workflows/"], "provision workflows", default_branch),
            "Sync workflows",
        )
        if target_branch != default_branch and not self.gh_client.get_branch_info(target_branch):
            self._require(self.gh_client.create_branch(target_branch, default_branch), "Create target branch")
        if scenario_files:
            additions = {
                path: self._get_content(path, content, substitution_map) for path, content in scenario_files.items()
            }
            self._require(
                self.gh_client.batch_sync(additions, [], "provision scenario files", target_branch), "Sync scenario"
            )
        elif target_branch != default_branch:
            self._require(
                self.gh_client.put_file(".scanner-probe", "probe\n", "scanner probe commit", target_branch),
                "Create PR comparison commit",
            )

    def _get_content(self, repo_path, content_or_path, substitution_map):
        """Reads and optionally patches file content."""
        content = content_or_path
        is_binary = False
        if isinstance(content_or_path, str) and os.path.exists(content_or_path):
            with open(content_or_path, "rb") as f:
                content = f.read()
                try:
                    content = content.decode("utf-8")
                    if substitution_map and (repo_path.endswith(".yml") or repo_path.endswith(".yaml")):
                        content = self._patch_yaml(content, substitution_map)
                except UnicodeDecodeError:
                    is_binary = True

        if is_binary:
            return content.decode("latin-1")
        return content

    def _patch_yaml(self, content: str, substitution_map: dict) -> str:
        """Replaces official action references with adversarial forks/tags."""
        import re

        patched_content = content
        for original, replacement in substitution_map.items():
            pattern = rf"uses:\s*['\"]?{re.escape(original)}['\"]?"
            replacement_str = f"uses: {replacement}"
            if re.search(pattern, patched_content):
                click.echo(click.style(f"  PATCHED: Swapping '{original}' -> '{replacement}'", fg="cyan"))
                patched_content = re.sub(pattern, replacement_str, patched_content)

        return patched_content

    def teardown(self):
        """Clean up a repository created by this provisioner, retaining ownership on failure."""
        if not self._owns_repo:
            return
        self._require(self.gh_client.delete_owned_repo(), "Delete owned repository")
        self._owns_repo = False
